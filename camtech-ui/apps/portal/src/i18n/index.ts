const dictionaries: Record<Locale, Partial<Record<MessageKey, string>>> = { en, ar };

let current: Locale = 'en';

export function setLocale(locale: Locale): void {
  current = locale;
}

/** True when `locale` has its own text for `key` (English is always complete). */
export function hasTranslation(locale: Locale, key: MessageKey): boolean {
  return dictionaries[locale][key] !== undefined;
}

/** All message keys. */
export const MESSAGE_KEYS = Object.keys(en) as MessageKey[];

/** Translates a UI string (English when the current locale has no text for it); `{name}` placeholders are filled from `vars`. */
export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const s = dictionaries[current][key] ?? en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : s;
}

/** Message key for a sign-in / user-management error code, when there is one. */
export function authErrorKey(code: string): MessageKey | null {
  const key = `auth.error.${code}`;
  return key in en ? (key as MessageKey) : null;
}
